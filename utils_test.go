func TestValidateRegexpWithEscapedComma(t *testing.T) {
	// The generator writes "{2,3}" as "{2\\,3}" in the struct tag.
	type plmnID struct {
		Mnc string `validate:"regexp=^[0-9]{2\\,3}$"`
	}
	cases := []struct {
		mnc     string
		wantErr bool
	}{
		{"01", false},
		{"001", false},
		{"1", true},
		{"0001", true},
		{"{2,3}", true},
	}
	for _, c := range cases {
		err := Validate(plmnID{Mnc: c.mnc})
		if (err != nil) != c.wantErr {
			t.Errorf("Validate(Mnc: %q) error = %v, wantErr %v", c.mnc, err, c.wantErr)
		}
	}
}

